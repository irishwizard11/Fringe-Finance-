export function speakIrishText(text: string, lang: 'ga' | 'en' = 'ga') {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) return;
  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text);
  const voices = window.speechSynthesis.getVoices();
  if (lang === 'ga') {
    const irishVoice = voices.find(
      (v) => v.lang.toLowerCase().includes('ga') || v.lang.toLowerCase().includes('en-ie')
    );
    if (irishVoice) {
      utterance.voice = irishVoice;
    }
    utterance.lang = 'ga-IE';
    utterance.rate = 0.92;
  } else {
    const ieVoice = voices.find((v) => v.lang.toLowerCase().includes('en-ie'));
    if (ieVoice) utterance.voice = ieVoice;
    utterance.lang = 'en-IE';
    utterance.rate = 0.98;
  }
  window.speechSynthesis.speak(utterance);
}
